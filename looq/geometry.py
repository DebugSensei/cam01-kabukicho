def point_in_polygon_m(point_m, polygon_m) -> bool:
    """Попадание точки в выпуклый или невыпуклый полигон на плане (ray casting).

    Без shapely: зависимость не нужна ради одного предиката, а поведение
    на границе должно быть нашим, а не библиотечным.
    """
    x, y = float(point_m[0]), float(point_m[1])
    poly = np.asarray(polygon_m, dtype=np.float64)
    n = len(poly)
    if n < 3:
        raise ValueError(f"полигон из {n} вершин")
    inside = False
    j = n - 1
    for i in range(n):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > y) != (yj > y):
            x_cross = (xj - xi) * (y - yi) / (yj - yi) + xi
            if x < x_cross:
                inside = not inside
        j = i
    return inside


def segment_normal_m(a_m, b_m, toward_m):
    """Единичная нормаль к отрезку, направленная в сторону точки toward_m.

    Нужна, чтобы построить apron — полосу ПЕРЕД витриной, а не за стеной.
    Сторону задаёт не знак в коде, а точка внутри улицы: так нельзя ошибиться
    полуплоскостью, что бы ни случилось с ориентацией плана.
    """
    a = np.asarray(a_m, dtype=np.float64)
    b = np.asarray(b_m, dtype=np.float64)
    d = b - a
    n = float(np.hypot(d[0], d[1]))
    if n < 1e-12:
        raise ValueError("отрезок вырожден в точку")
    normal = np.array([-d[1], d[0]]) / n
    mid = (a + b) / 2.0
    if float(normal @ (np.asarray(toward_m, dtype=np.float64) - mid)) < 0:
        normal = -normal
    return normal


def ray_segment_intersection_m(origin_m, direction_deg, seg_a_m, seg_b_m,
                               max_dist: float):
    """Пересечение луча с отрезком. Возвращает (расстояние, точка) или (None, None).

    Луч выходит из origin_m в направлении direction_deg (конвенция углов модуля)
    и имеет длину не более max_dist.
    """
    o = np.asarray(origin_m, dtype=np.float64)
    rad = np.deg2rad(float(direction_deg))
    d = np.array([np.cos(rad), np.sin(rad)])
    a = np.asarray(seg_a_m, dtype=np.float64)
    b = np.asarray(seg_b_m, dtype=np.float64)
    e = b - a

    denom = d[0] * (-e[1]) - d[1] * (-e[0])
    if abs(denom) < 1e-12:
        return None, None                    # луч параллелен отрезку
    rhs = a - o
    t = (rhs[0] * (-e[1]) - rhs[1] * (-e[0])) / denom     # вдоль луча
    u = (d[0] * rhs[1] - d[1] * rhs[0]) / denom           # вдоль отрезка
    if t < 0 or t > max_dist or not (0.0 <= u <= 1.0):
        return None, None
    return float(t), o + t * d


def sector_hits_segment_m(origin_m, direction_deg, half_width_deg,
                          seg_a_m, seg_b_m, max_dist: float):
    """Пересечение СЕКТОРА ориентации с отрезком фасада.

    Определение из CLAUDE.md: луч длиной не более max_dist, расширенный в сектор
    полушириной half_width_deg — угловой НЕОПРЕДЕЛЁННОСТЬЮ оценки yaw, а не
    порогом решения.

    Проверяются три луча: центральный и оба края сектора. Этого достаточно:
    отрезок выпуклый, и если сектор его пересекает, то пересекает и один из
    трёх лучей либо отрезок целиком лежит внутри сектора — последний случай
    ловится проверкой концов отрезка на попадание в сектор.

    Возвращает (расстояние до ближайшего попадания, точка) или (None, None).
    """
    best = (None, None)
    for delta in (-float(half_width_deg), 0.0, float(half_width_deg)):
        dist, pt = ray_segment_intersection_m(origin_m, float(direction_deg) + delta,
                                              seg_a_m, seg_b_m, max_dist)
        if dist is not None and (best[0] is None or dist < best[0]):
            best = (dist, pt)
    if best[0] is not None:
        return best

    # Отрезок целиком внутри сектора: лучи его не задели, но концы видны.
    o = np.asarray(origin_m, dtype=np.float64)
    for end in (np.asarray(seg_a_m, dtype=np.float64), np.asarray(seg_b_m, dtype=np.float64)):
        v = end - o
        dist = float(np.hypot(v[0], v[1]))
        if dist > max_dist or dist < 1e-12:
            continue
        ang = float(np.degrees(np.arctan2(v[1], v[0])) % 360.0)
        if abs(float(yaw_diff_deg(ang, direction_deg))) <= float(half_width_deg):
            if best[0] is None or dist < best[0]:
                best = (dist, end)
    return best


def grazing_angle_deg(hit_point_m, origin_m, seg_a_m, seg_b_m) -> float:
    """Угол падения луча на фасад, отсчитанный от НОРМАЛИ, в градусах [0, 90].

    Больше grazing_max_deg означает, что фасад виден с ребра: пересечение
    формально есть, но полагаться на него нельзя (правило 7).
    """
    o = np.asarray(origin_m, dtype=np.float64)
    hit = np.asarray(hit_point_m, dtype=np.float64)
    ray = hit - o
    n = float(np.hypot(ray[0], ray[1]))
    if n < 1e-12:
        return 90.0
    ray = ray / n
    normal = segment_normal_m(seg_a_m, seg_b_m, o)
    cos = abs(float(ray @ normal))
    return float(np.degrees(np.arccos(np.clip(cos, 0.0, 1.0))))


