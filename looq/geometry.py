def apply_homography(h_px_to_m, pts_px) -> np.ndarray:
    """Переводит точки из frame_px в plane_m.

    Направление преобразования зафиксировано: матрица из calib/homography.json
    всегда переводит ПИКСЕЛИ В МЕТРЫ. Обратное направление в контрактах не хранится,
    чтобы нельзя было перепутать сторону.

    h_px_to_m : (3, 3)
    pts_px    : (N, 2), координаты frame_px
    возвращает: (N, 2), координаты plane_m
    """
    h = np.asarray(h_px_to_m, dtype=np.float64)
    if h.shape != (3, 3):
        raise ValueError(f"гомография должна быть 3x3, получено {h.shape}")
    pts = np.asarray(pts_px, dtype=np.float64)
    if pts.ndim != 2 or pts.shape[1] != 2:
        raise ValueError(f"ожидался массив точек (N, 2), получено {pts.shape}")

    homo = np.concatenate([pts, np.ones((pts.shape[0], 1))], axis=1)  # (N, 3)
    out = homo @ h.T
    w = out[:, 2:3]
    if np.any(np.abs(w) < 1e-12):
        raise ValueError(
            "точка проецируется на линию горизонта (w ~ 0): за пределами ROI "
            "плоскость земли не определена, оценка расстояния бессмысленна"
        )
    return out[:, :2] / w


# --------------------------------------------------------------------------- #
# Независимая проверка масштаба: ширина улицы
# --------------------------------------------------------------------------- #

def _point_to_line_distance_m(point_m, line_a_m, line_b_m) -> float:
    """Перпендикулярное расстояние от точки до прямой через две точки, в метрах."""
    p = np.asarray(point_m, dtype=np.float64)
    a = np.asarray(line_a_m, dtype=np.float64)
    b = np.asarray(line_b_m, dtype=np.float64)
    ab = b - a
    length = float(np.hypot(ab[0], ab[1]))
    if length < 1e-9:
        raise ValueError("линия основания фасада вырождена в точку")
    return float(abs(np.cross(ab, p - a)) / length)


def facade_lines_separation_m(line_a_m, line_b_m) -> dict[str, float]:
    """Расстояние между двумя линиями оснований фасадов на плане, в метрах.

    Это ширина улицы, измеренная НАШЕЙ гомографией. Сравнивается в гейте S1
    с независимым контрольным значением (спутниковый снимок). Контрольное
    значение НЕ участвует в подгонке гомографии — иначе проверка проверяла бы
    сама себя.

    line_a_m, line_b_m : по две точки (x_m, y_m) — основание фасада на плане.

    Фасады параллельны лишь приблизительно, поэтому расстояние меряется
    симметрично: каждый конец каждой линии до прямой, проходящей через другую.
    Разброс между четырьмя измерениями сам по себе диагностика — если он велик,
    линии не параллельны и «ширина улицы» плохо определена.
    """
    a = np.asarray(line_a_m, dtype=np.float64).reshape(2, 2)
    b = np.asarray(line_b_m, dtype=np.float64).reshape(2, 2)

    dists = [_point_to_line_distance_m(a[i], b[0], b[1]) for i in range(2)]
    dists += [_point_to_line_distance_m(b[i], a[0], a[1]) for i in range(2)]

    dir_a = a[1] - a[0]
    dir_b = b[1] - b[0]
    cos = float(np.clip(
        abs(np.dot(dir_a, dir_b)) / (np.linalg.norm(dir_a) * np.linalg.norm(dir_b)),
        -1.0, 1.0))
    return {
        "width_mean_m": float(np.mean(dists)),
        "width_min_m": float(np.min(dists)),
        "width_max_m": float(np.max(dists)),
        "width_spread_m": float(np.max(dists) - np.min(dists)),
        "lines_angle_deg": float(np.degrees(np.arccos(cos))),
    }


# --------------------------------------------------------------------------- #
# Разброс роста: единственная часть проверки роста, которая независима
# --------------------------------------------------------------------------- #

def height_spread_stats(heights_m) -> dict[str, float]:
    """Медиана и РАЗБРОС оценок роста по пилотным трекам, в метрах.

    Медиана здесь справочная: масштаб гомографии подбирается ИМЕННО ПО НЕЙ,
    поэтому её попадание в диапазон почти тавтологично и масштаб не проверяет.
    Она детектирует только грубый сбой подгонки.

    Разброс — другое дело. IQR и p90-p10 масштабом не задаются, их задаёт
    геометрия: при кривой гомографии оценка роста плывёт с глубиной, и разброс
    разъезжается даже когда медиана стоит на месте. Это настоящая независимая
    проверка, и в гейте S1 она вынесена отдельной строкой.
    """
    h = np.asarray(heights_m, dtype=np.float64)
    h = h[np.isfinite(h)]
    if h.size < 2:
        raise ValueError(
            f"для разброса роста нужно минимум 2 конечных значения, получено {h.size} "
            f"(правило 8: не возвращаем ноль как успех)"
        )
    q10, q25, q50, q75, q90 = np.percentile(h, [10, 25, 50, 75, 90])
    return {
        "n": int(h.size),
        "median_m": float(q50),
        "iqr_m": float(q75 - q25),
        "p10_m": float(q10),
        "p90_m": float(q90),
        "p90_p10_m": float(q90 - q10),
    }


