def normalize_yaw_deg(yaw_deg):
    """Приводит угол к диапазону [0, 360) — единственному допустимому в контрактах."""
    return np.mod(np.asarray(yaw_deg, dtype=np.float64), 360.0)


def yaw_diff_deg(a_deg, b_deg):
    """Кратчайшая знаковая разница a - b в диапазоне (-180, 180].

    Нужна для MAE угла в гейте S5: наивное вычитание даёт 359 вместо 1.
    """
    d = np.mod(np.asarray(a_deg, dtype=np.float64)
               - np.asarray(b_deg, dtype=np.float64) + 180.0, 360.0) - 180.0
    # np.mod даёт [-180, 180); переносим -180 в +180, чтобы диапазон был замкнут сверху.
    return np.where(d == -180.0, 180.0, d)


def circular_median_deg(yaw_deg):
    """Круговая медиана углов: угол, минимизирующий сумму угловых расстояний.

    Обычная медиана на углах ломается на переходе через 0/360: медиана
    [359, 1, 3] равна 3, а правильный ответ — 1. Здесь минимум ищется перебором
    по самим значениям выборки; для окна в 5-9 элементов это дешевле любой
    оптимизации и не зависит от начального приближения.
    """
    a = np.asarray(yaw_deg, dtype=np.float64)
    a = a[np.isfinite(a)]
    if a.size == 0:
        return np.nan
    # Матрица попарных угловых расстояний: строка i — сумма расстояний от a[i].
    d = np.abs(np.mod(a[None, :] - a[:, None] + 180.0, 360.0) - 180.0).sum(axis=1)
    return float(a[int(np.argmin(d))])


def smooth_yaw_series_deg(yaw_deg, window: int):
    """Скользящая круговая медиана по одному треку. Возвращает НОВЫЙ массив.

    ЗАЧЕМ. Замер 2026-09-08 по 213 287 переходам между соседними кадрами:
    медиана скачка угла 4.3 градуса, но **1.0 % переходов — это разворот
    больше 90 градусов**. Человек не разворачивается на 180 градусов за 0.1 с
    и обратно, поэтому такой переход — ошибка модели позы, а не движение.

    Почему медиана по времени, а не фильтр по уверенности: перевороты по
    уверенности НЕ отделяются. В корзине conf 0.9-1.0, где лежит 85 % данных,
    переворотов 0.6 %; отсев по conf >= 0.8 убирает 7 % строк и меняет долю
    переворотов с 1.0 % до 0.7 %. Модель ошибается уверенно.

    Почему медиана, а не среднее: одиночный выброс на 180 градусов сдвигает
    круговое среднее на десятки градусов, а медиану — нет.

    Цена, измеренная на той же ручной разметке (labels/s5_orient_50.jsonl,
    n = 50): MAE 21.21 -> 20.40 градуса, 95 % бутстрэп [15.5, 28.8] ->
    [15.0, 27.8], p90 36.1 -> 34.0. То есть сглаживание не подгонка: оно
    улучшает точность против отложенной ручной разметки, а не только вид.

    Пропуски (null) сохраняются на своих местах: окно строится по измеренным
    значениям трека, «не измерено» не превращается в число (правило 7).
    """
    y = np.asarray(yaw_deg, dtype=np.float64).copy()
    w = int(window)
    if w < 3:
        return y                       # окно меньше 3 не сглаживает ничего
    ok = np.isfinite(y)
    if ok.sum() < 3:
        return y
    v = y[ok]
    out = v.copy()
    half = w // 2
    for i in range(v.size):
        out[i] = circular_median_deg(v[max(0, i - half):min(v.size, i + half + 1)])
    y[ok] = out
    return y


def yaw_to_unit_vector_m(yaw_deg):
    """Единичный вектор направления в plane_m по конвенции углов из шапки модуля."""
    rad = np.deg2rad(normalize_yaw_deg(yaw_deg))
    return np.stack([np.cos(rad), np.sin(rad)], axis=-1)


