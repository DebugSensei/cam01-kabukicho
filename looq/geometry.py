def polygon_cross_signs(poly_px) -> np.ndarray:
    """Векторные произведения соседних рёбер многоугольника.

    Одинаковые знаки у всех = выпуклый И простой. Одна проверка закрывает и
    выпуклость, и самопересечение: «бабочка» даёт разные знаки. Ноль означает
    три точки на одной прямой, то есть вырождение.

    Живёт здесь, а не в двух местах: предикат используют и обводка зон
    (scripts/pick_zones.py), и калибровка по прямоугольнику мостовой
    (looq.calib.homography_from_ground_rect), а разъехавшиеся копии одного
    геометрического правила — верный способ получить разное поведение.
    """
    pts = np.asarray(poly_px, dtype=np.float64)
    n = len(pts)
    if n < 3:
        raise ValueError(f"для многоугольника нужно >=3 точек, получено {n}")
    out = []
    for i in range(n):
        a = pts[(i + 1) % n] - pts[i]
        b = pts[(i + 2) % n] - pts[(i + 1) % n]
        out.append(a[0] * b[1] - a[1] * b[0])
    return np.asarray(out, dtype=np.float64)


