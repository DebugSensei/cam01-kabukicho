#: Откуда взята опорная точка человека на плоскости земли (колонка foot_source S4).
FOOT_SOURCES: tuple[str, ...] = ("ankle", "bbox_bottom", "hip_est")

#: Прямое измерение или косвенная оценка. В толпе ноги перекрыты, и опорная точка
#: восстанавливается от бёдер или от низа рамки — это НЕ измерение, и по контракту
#: оно обязано быть видно в данных. S8 выводит долю косвенных значений отдельным
#: числом, а не растворяет её в среднем.
FOOT_SOURCE_IS_DIRECT: dict[str, bool] = {
    "ankle": True,          # голеностоп виден в позе, точка стоит на земле
    "bbox_bottom": False,   # низ рамки != стопа при перекрытии и обрезке кадром
    "hip_est": False,       # экстраполяция вниз от бёдер по оценке роста
}


def indirect_share(foot_sources: Iterable[str]) -> float:
    """Доля косвенно полученных опорных точек. Пустой вход — ошибка, не ноль."""
    vals = list(foot_sources)
    if not vals:
        raise ValueError(
            "indirect_share() получил пустую последовательность: доля по нулю "
            "строк не определена (правило 8, не возвращаем 0 как успех)"
        )
    unknown = sorted({v for v in vals if v not in FOOT_SOURCE_IS_DIRECT})
    if unknown:
        raise ValueError(f"неизвестные значения foot_source: {unknown}")
    return sum(1 for v in vals if not FOOT_SOURCE_IS_DIRECT[v]) / len(vals)


