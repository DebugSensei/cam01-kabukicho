# Запись. ЕДИНСТВЕННЫЕ функции проекта, которым разрешено кодировать и
# записывать изображение. Всё остальное зовёт их.
# --------------------------------------------------------------------------- #

def encode_image(img: np.ndarray, suffix: str = ".jpg",
                 quality: int = 92) -> bytes:
    """Обезличивает и кодирует. Единственная точка кодирования в проекте.

    Копию не делает намеренно: вызывающая сторона должна видеть, что её
    массив изменился. Скрытая копия позволила бы записать обезличенное, а
    дальше работать с необезличенным и записать его чем-то другим.
    """
    anonymise(img)
    params: list[int] = []
    s = suffix.lower()
    if s in (".jpg", ".jpeg"):
        params = [int(cv2.IMWRITE_JPEG_QUALITY), int(quality)]
    elif s == ".webp":
        params = [int(cv2.IMWRITE_WEBP_QUALITY), int(quality)]
    ok, buf = cv2.imencode(s, img, params)
    if not ok:
        raise AnonymiseError(f"cv2.imencode не смог закодировать {suffix}")
    return buf.tobytes()


def save_image(path: str | Path, img: np.ndarray, quality: int = 92) -> int:
    """Обезличивает и записывает. Единственная точка записи в проекте.

    Возвращает число записанных байт. Запись атомарная: недописанный файл на
    диске выглядел бы как готовое изображение.
    """
    p = Path(path)
    data = encode_image(img, suffix=p.suffix or ".jpg", quality=quality)
    p.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_bytes(p, data)
    return len(data)


def data_uri(img: np.ndarray, quality: int = 92) -> str:
    """Обезличенный кадр как data-URI для встраивания в страницу."""
    return ("data:image/jpeg;base64,"
            + base64.b64encode(encode_image(img, ".jpg", quality)).decode())


def save_figure(fig, path: str | Path, dpi: int = 100) -> int:
    """Фигура matplotlib — через тот же путь, что и кадры.

    Отдельный путь для графиков был бы исключением, а исключение — лазейка:
    «это же просто график» звучит одинаково и когда в фигуре только точки, и
    когда в неё вставлен imshow кадра. Фигура растеризуется в массив и идёт
    в save_image наравне со всем остальным. Ценой одного прохода детектора,
    который на графике без людей возвращает ноль рамок.
    """
    fig.canvas.draw()
    rgba = np.asarray(fig.canvas.buffer_rgba())
    return save_image(path, cv2.cvtColor(rgba, cv2.COLOR_RGBA2BGR), quality=95)
