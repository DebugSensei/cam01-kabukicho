"""Единственный путь записи изображения в проекте.

Зачем модуль существует
-----------------------
Правило 9 CLAUDE.md держалось на дисциплине: обезличивание было отдельным
шагом, который вызывающая сторона могла выполнить, а могла забыть. Забыла.
Измерено 2026-09-06: у ``scripts/make_dashboard.py:b64_img`` параметр
``anonymise`` имел значение по умолчанию ``False``; вызов для пруфов его
передавал, вызов для трёх больших фигур — нет, и в опубликованном на GitHub
Pages ``out/dashboard.html`` оказалось 14 изображений из 51 с резкими лицами,
в одном 27 лицевых кейпоинтов из 31.

Дефект был не в той странице. Дефект был в том, что обезличивание — это
шаг, а не путь. Здесь он сделан путём: чтобы записать изображение, надо
позвать ``save_image``/``encode_image``, а они обезличивают ВСЕГДА. Флага
«не обезличивать» нет и быть не должно — он и был дырой.

Почему нет исключения для картинок без людей
--------------------------------------------
Соблазн: графики matplotlib людей не содержат, зачем им детектор. Но
исключение по типу картинки — это ровно та лазейка, которую модуль
закрывает: «это же просто график» звучит одинаково убедительно и когда
правда, и когда в график вставлен ``imshow`` кадра. Замер снимает вопрос
ценой: проход детектора по изображению без людей стоит около 0.1 с и
возвращает ноль рамок. Платить 0.1 с за отсутствие исключения — дёшево.

Почему детектор, а не фиксированная верхняя доля
------------------------------------------------
``looq.evidence.blur_face_region`` мажет верхнюю долю кропа. На кропе, где
голова в эту долю не попала — наклон, перекрытие, срез краем, — лицо
остаётся. Замер: 11 пруфов, вшитых в дашборд ЧЕРЕЗ повторное размытие по
доле, всё равно дали по 2-4 резких лицевых кейпоинта. Детектор с позой
находит голову там, где она есть. Доля остаётся ЗАПАСНЫМ путём для человека,
у которого поза кейпоинтов не дала, и не убирается.

Порядок обезличивания
---------------------
Пикселизация, затем гаусс. Не наоборот и не только гаусс: свёртка обратима,
деблюр по чистой гауссиане восстанавливает черты. Пикселизация уничтожает
информацию мельче блока безвозвратно. Реализация — в ``looq.evidence``,
здесь она только применяется к найденным рамкам.
"""

from __future__ import annotations

import base64
from pathlib import Path
from typing import Any, Sequence

import cv2
import numpy as np

from looq.evidence import EvidenceError, blur_face_region
from looq.io import ConfigError, atomic_write_bytes, load_config

# --------------------------------------------------------------------------- #
# Пороги. Здесь, а не в yaml, потому что это не настройка качества, а часть
# гарантии приватности: поднять их из конфига значило бы вернуть возможность
# отключить обезличивание, не трогая код.
# --------------------------------------------------------------------------- #

#: Порог детектора для ПОИСКА ЛЮДЕЙ ПОД РАЗМЫТИЕ. Намеренно много ниже
#: рабочего порога стадии S3 (0.25): цена ложной рамки — размытый кусок
#: асфальта, цена пропуска — лицо в публикации. Замер на восьми кадрах: при
#: 0.25 детектор пропускал людей, чьи лица модель позы находила уверенно.
ANON_CONF = 0.05

#: Рамки ниже этой высоты не размываются: на 20 px человек занимает меньше,
#: чем ядро размытия, и «лица» там нет — есть 3-4 пикселя тона кожи.
ANON_MIN_BOX_H = 20

#: Кейпоинты лица в COCO: нос, глаза, уши.
FACE_KP = (0, 1, 2, 3, 4)

#: Порог уверенности кейпоинта, при котором он участвует в построении рамки
#: головы. Ниже рабочего 0.5 по той же причине, что и ANON_CONF.
FACE_KP_CONF = 0.20

#: Насколько раздуть рамку вокруг кейпоинтов лица, в долях её размера.
#: Кейпоинты отмечают точки, а закрыть надо голову: волосы, подбородок, уши.
HEAD_PAD = 0.9

#: Вид рамки помечается ЯВНО при сборе, а не угадывается потом по пропорции.
#: Прежняя версия в render_overlay считала головой всё, что вытянуто
#: вертикально слабее 1.7, и держалась на запасе 0.14: уменьши HEAD_PAD, и
#: голова молча стала бы «человеком» — размылась бы её верхняя треть, а лицо
#: осталось.
KIND_PERSON, KIND_HEAD = "person", "head"

#: Откуда берутся параметры размытия. Тот же файл, что у пруфов: страница и
#: кроп на диске обязаны быть размыты одинаково, иначе «текущий порог»
#: означает разное в разных местах.
PRIVACY_CONFIG = "configs/evidence.yaml"
PRIVACY_KEYS = ("face_blur_top_frac", "blur_kernel_frac", "blur_sigma_frac",
                "pixelate_factor")

#: Веса. Обе сети нужны: одна ошибается там, где другая справляется.
DETECT_WEIGHTS = Path("models/yolo11m.pt")
POSE_WEIGHTS = Path("models/yolo11m-pose.pt")


class AnonymiseError(RuntimeError):
    """Обезличивание невозможно выполнить. Записывать изображение нельзя."""


# --------------------------------------------------------------------------- #
# Модели и параметры приватности: грузятся один раз на процесс
# --------------------------------------------------------------------------- #

_MODELS: tuple[Any, ...] | None = None
_PRIV: dict[str, float] | None = None
_DEVICE: str = "cpu"


def models_available() -> bool:
    """Есть ли на машине веса обеих сетей.

    Для тестов и гейтов, которые обязаны пропускаться на чистом клоне, а не
    падать. Сама запись изображения при отсутствии весов падает: молча
    записать необезличенный кадр — это то, ради чего модуль написан.
    """
    return DETECT_WEIGHTS.is_file() and POSE_WEIGHTS.is_file()


def set_device(device: str) -> None:
    """Куда считать. Влияет только на скорость, не на результат."""
    global _DEVICE
    _DEVICE = str(device)


def load_privacy() -> dict[str, float]:
    """Параметры размытия из configs/evidence.yaml. Дефолтов нет (правило 5)."""
    global _PRIV
    if _PRIV is not None:
        return _PRIV
    try:
        cfg = load_config(PRIVACY_CONFIG)
    except (ConfigError, FileNotFoundError) as e:
        raise AnonymiseError(
            f"не прочитан {PRIVACY_CONFIG}: {e}. Без параметров размытия "
            f"запись изображения запрещена") from e
    priv = cfg.get("privacy") or {}
    missing = [k for k in PRIVACY_KEYS if k not in priv]
    if missing:
        raise AnonymiseError(
            f"в {PRIVACY_CONFIG} нет ключей приватности {missing}: писать "
            f"изображение с тем размытием, какое случайно окажется, нельзя "
            f"(правило 8)")
    _PRIV = {k: priv[k] for k in PRIVACY_KEYS}
    return _PRIV


def load_models() -> tuple[Any, ...]:
    """Детектор и поза. Падает громко, если весов нет."""
    global _MODELS
    if _MODELS is not None:
        return _MODELS
    missing = [str(p) for p in (DETECT_WEIGHTS, POSE_WEIGHTS) if not p.is_file()]
    if missing:
        raise AnonymiseError(
            f"нет весов {missing}. Они нужны не для красоты: без них нечем "
            f"найти лица, а записать изображение необезличенным нельзя")
    from ultralytics import YOLO           # тяжёлый импорт — только при нужде
    _MODELS = (YOLO(str(DETECT_WEIGHTS)), YOLO(str(POSE_WEIGHTS)))
    return _MODELS


# --------------------------------------------------------------------------- #
# Поиск того, что закрывать
# --------------------------------------------------------------------------- #

def _head_boxes_from_pose(res) -> list[tuple[float, float, float, float]]:
    """Рамки вокруг найденных кейпоинтов лица.

    Полоса в верхней доле рамки человека — приближение, и оно ломается на
    наклонённой голове: замер на кадре f060369 показал лицо, у которого нос
    внутри полосы, а подбородок под её краем, с резкой границей ровно по лицу.
    Кейпоинты говорят, где голова на самом деле.
    """
    if res.keypoints is None or res.keypoints.conf is None:
        return []
    xy = np.asarray(res.keypoints.xy.cpu())
    cf = np.asarray(res.keypoints.conf.cpu())
    out: list[tuple[float, float, float, float]] = []
    for pi in range(cf.shape[0]):
        pts = [xy[pi, j] for j in FACE_KP if cf[pi, j] >= FACE_KP_CONF]
        if not pts:
            continue
        pts = np.asarray(pts, dtype=np.float64)
        x0, y0 = pts[:, 0].min(), pts[:, 1].min()
        x1, y1 = pts[:, 0].max(), pts[:, 1].max()
        # У профиля видны один глаз и ухо: рамка вырождается в точку, и
        # раздувать её от нулевого размера нечего. Берём запас от роста.
        span = max(x1 - x0, y1 - y0, 12.0)
        pad = span * HEAD_PAD
        out.append((x0 - pad, y0 - pad, x1 + pad, y1 + pad))
    return out


def _boxes_union(models: Sequence[Any], img: np.ndarray,
                 imgsz: int) -> list[tuple[np.ndarray, str]]:
    """Что закрывать: (рамка, вид).

    Рамка человека добавляется ВСЕГДА, независимо от того, нашлись ли у него
    кейпоинты головы. Рамки голов идут СВЕРХ, а не вместо: если поза не
    сработала — перекрытый человек, спина, край кадра, — остаётся полоса, и
    человек не уходит незакрытым. Это обязательный запасной путь.

    Дубликаты не убираются: размыть одну голову дважды безвредно, а выкидывать
    пересечения значило бы рисковать ради экономии, которой здесь нет.
    """
    out: list[tuple[np.ndarray, str]] = []
    for m in models:
        r = m.predict(img, imgsz=imgsz, conf=ANON_CONF, device=_DEVICE,
                      classes=[0], verbose=False)[0]
        if r.boxes is not None and len(r.boxes):
            for b in np.asarray(r.boxes.xyxy.cpu(), dtype=np.float64):
                out.append((b, KIND_PERSON))
        for hb in _head_boxes_from_pose(r):
            out.append((np.asarray(hb, dtype=np.float64), KIND_HEAD))
    return out


#: Разрешение, на котором ГЕЙТ ищет лица (tests/test_single_image_write.py и
#: tests/test_overlay_anonymised.py). Обезличиватель обязан смотреть не хуже:
#: иначе он не увидит того, что увидит проверка, и это не теория.
CHECK_IMGSZ = 1280


def _imgsz_for(img: np.ndarray) -> int:
    """Разрешение инференса под размер картинки, но НЕ НИЖЕ, чем у проверки.

    Соблазн считать кроп 51x190 на 320 — быстрее и «по размеру». Замер
    2026-09-06 показал цену: на 320 модель позы не находила на таком кропе
    ни одного кейпоинта головы, оставался только запасной путь — верхние
    30 % рамки, — а лицо лежало на 82 % высоты, и кроп уходил в дашборд
    резким. Тот же кроп на 1280 даёт нос с уверенностью 0.95.

    Правило: обезличиватель смотрит с тем же разрешением, что и гейт, или
    выше, если картинка больше. Кратно 32, как требует YOLO.
    """
    long_side = max(img.shape[0], img.shape[1])
    target = min(1600, max(CHECK_IMGSZ, long_side))
    return int(round(target / 32)) * 32


# --------------------------------------------------------------------------- #
# Обезличивание
# --------------------------------------------------------------------------- #

def anonymise(img: np.ndarray) -> tuple[int, int]:
    """Закрывает голову каждому найденному человеку. Правит массив НА МЕСТЕ.

    Единственный публичный вход. Аргументов, кроме картинки, нет намеренно:
    подменить модель значило бы получить обратно отключаемое обезличивание —
    ровно то, что модуль закрывает. Подмена нужна только тестам, и им дана
    отдельная внутренняя дверь ``_anonymise_with``, которую гейт
    ``tests/test_single_image_write.py`` не пускает в рабочий код.

    Возвращает (закрыто рамок, отброшено). Отброшенная рамка — это либо
    слишком мелкая, либо уже однородная область: обе не несут лица.

    Вызывать ДО отрисовки боксов, стрелок и подписей. Иначе размытие затрёт
    разметку, а не лицо, а модель позы на готовом кадре начнёт ставить
    кейпоинты на саму разметку — замер поймал «ухо» с уверенностью 0.32 на
    зелёной надписи, где лица нет вовсе.
    """
    if img is None or getattr(img, "size", 0) == 0:
        raise AnonymiseError("пустое изображение: обезличивать нечего, "
                             "но и записывать нечего")
    return _anonymise_with(img, load_models(), load_privacy(), _imgsz_for(img))


def _anonymise_with(img: np.ndarray, models: Sequence[Any], priv: dict,
                    imgsz: int) -> tuple[int, int]:
    """Реализация с явными зависимостями. Для тестов и для render_overlay,
    который уже держит загруженные модели и не должен грузить их второй раз."""
    models = models if isinstance(models, (tuple, list)) else (models,)
    done = skipped = 0
    for box, kind in _boxes_union(models, img, imgsz):
        x1, y1, x2, y2 = [int(round(v)) for v in box]
        x1, y1 = max(0, x1), max(0, y1)
        x2, y2 = min(img.shape[1], x2), min(img.shape[0], y2)
        if x2 - x1 < 4 or y2 - y1 < ANON_MIN_BOX_H:
            skipped += 1
            continue
        # У рамки головы размывается ВСЯ площадь: она и есть голова, брать
        # долю внутри неё неоткуда. У рамки человека — верхняя доля из
        # конфига, и это запасной путь для тех, у кого позу не нашли.
        top = 1.0 if kind == KIND_HEAD else float(priv["face_blur_top_frac"])
        try:
            blurred, _ = blur_face_region(
                img[y1:y2, x1:x2].copy(),
                top_frac=top,
                kernel_frac=float(priv["blur_kernel_frac"]),
                sigma_frac=float(priv["blur_sigma_frac"]),
                pixelate_factor=int(priv["pixelate_factor"]))
        except EvidenceError:
            skipped += 1              # область уже однородна, лица там нет
            continue
        img[y1:y2, x1:x2] = blurred
        done += 1
    return done, skipped


